-- Lab 9: tài khoản đăng nhập. Đặt tên app_user vì "user" là từ khoá của Postgres.
-- Không seed admin ở đây: migration chạy cả ở prod, mật khẩu mặc định sẽ thành lỗ hổng.
-- Tài khoản mẫu cho dev do DevSampleDataSeeder tạo.
CREATE TABLE app_user (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50)  NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,                       -- BCrypt hash (60 ký tự), không bao giờ lưu plain text
    role     VARCHAR(20)  NOT NULL CHECK (role IN ('USER', 'ADMIN'))
);
